  def install
    # cryptography builds a Rust extension whose openssl-sys build script cannot
    # locate Homebrew's OpenSSL on Linux, even with it on PKG_CONFIG_PATH.
    ENV["OPENSSL_DIR"] = formula_opt_prefix("openssl@3")

    # pillow's setup.py does its own header search rather than honouring
    # superenv, so hand it the zlib prefix directly on Linux.
    ENV["ZLIB_ROOT"] = formula_opt_prefix("zlib-ng-compat") if OS.linux?

    virtualenv_install_with_resources
  end

  test do
    assert_match "usage: vastai", shell_output("#{bin}/vastai --help")
    assert_equal version.to_s, shell_output("#{bin}/vastai --version").strip

    # A Homebrew install is not the managed (curl | bash) install, so the CLI
    # must decline to self-update rather than fight brew for the binary.
    assert_match "cannot self-update", shell_output("#{bin}/vastai update 2>&1", 1)
  end
